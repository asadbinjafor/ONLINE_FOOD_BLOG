ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE restaurant_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE food_experience_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE food_experience_comments ENABLE ROW LEVEL SECURITY;
